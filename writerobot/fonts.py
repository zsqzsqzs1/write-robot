# 小写字母 -> 大写字母（小型大写风格，绘图机常用且无需额外字形数据）
_LOWERCASE_TO_UPPER = {
    "a": "A", "b": "B", "c": "C", "d": "D", "e": "E", "f": "F", "g": "G", "h": "H",
    "i": "I", "j": "J", "k": "K", "l": "L", "m": "M", "n": "N", "o": "O", "p": "P",
    "q": "Q", "r": "R", "s": "S", "t": "T", "u": "U", "v": "V", "w": "W", "x": "X",
    "y": "Y", "z": "Z",
}

#: 字体度量：基线上方 / 下方范围
GLYPH_METRICS = {
    "ascent": 1.0,
    "descent": -0.22,
    "x_height": 0.70,
}


def get_glyph(char: str) -> Tuple[List[Stroke], float] | None:
    """获取字符的字形数据，找不到时返回 ``None``。"""
    if char in LATIN_GLYPHS:
        strokes, advance = LATIN_GLYPHS[char]
        return ([list(s) for s in strokes], advance)
    mapped = _LOWERCASE_TO_UPPER.get(char.lower())
    if mapped:
        strokes, advance = LATIN_GLYPHS[mapped]
        # 小型大写：高度缩到 x_height，宽度同比缩放
        scale = GLYPH_METRICS["x_height"]
        return ([[(x * scale, y * scale) for x, y in s] for s in strokes], advance * scale)
    return None
